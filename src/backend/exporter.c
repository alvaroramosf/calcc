/**
 * @file exporter.c
 * @brief Implementation of multi-format exporters for the Elektronika MK-56.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "exporter.h"

void recorder_reset(StepRecorder *rec) {
    if (rec) {
        rec->count = 0;
    }
}

void recorder_add_step(StepRecorder *rec, uint8_t addr, uint8_t opcode,
                       const char *vfd_code, const char *mnemonic,
                       const char *keystrokes, const char *desc) {
    if (!rec || rec->count >= MAX_RECORDED_STEPS) return;

    ProgramStep *s = &rec->steps[rec->count++];
    s->address = addr;
    s->opcode = opcode;
    snprintf(s->vfd_code, sizeof(s->vfd_code), "%s", vfd_code ? vfd_code : "  ");
    snprintf(s->mnemonic, sizeof(s->mnemonic), "%s", mnemonic ? mnemonic : "");
    snprintf(s->keystrokes, sizeof(s->keystrokes), "%s", keystrokes ? keystrokes : "");
    snprintf(s->description, sizeof(s->description), "%s", desc ? desc : "");
}

int utf8_display_width(const char *s) {
    if (!s) return 0;
    int len = 0;
    while (*s) {
        if ((*s & 0xC0) != 0x80) {
            len++;
        }
        s++;
    }
    return len;
}

void fprint_utf8_padded(FILE *out, const char *s, int target_width) {
    if (!out) return;
    if (!s) s = "";
    int vis_len = utf8_display_width(s);
    fputs(s, out);
    for (int i = vis_len; i < target_width; i++) {
        fputc(' ', out);
    }
}

void export_to_asm(FILE *out, const TargetCaps *caps, const StepRecorder *rec) {
    if (!out || !caps || !rec) return;

    fprintf(out, "; ==========================================================\n");
    fprintf(out, "; Target: %s\n", caps->display_name);
    fprintf(out, "; Architecture: %s\n", caps->architecture);
    fprintf(out, "; Max Capacity: %u steps, %u memory registers\n",
            caps->max_program_steps, caps->data_registers_count);
    fprintf(out, "; Generated by Micro C Transpiler\n");
    fprintf(out, "; ==========================================================\n");
    fprintf(out, "; Step | VFD  | Hex   | Cyrillic | Description\n");
    fprintf(out, "; ----------------------------------------------------------\n");

    for (int i = 0; i < rec->count; i++) {
        const ProgramStep *s = &rec->steps[i];
        fprintf(out, "  %02u:   ", s->address);
        fprint_utf8_padded(out, s->vfd_code, 4);
        fprintf(out, "  0x%02X   ", s->opcode);
        fprint_utf8_padded(out, s->mnemonic, 8);
        fprintf(out, "  ; %s\n", s->description);
    }

    fprintf(out, "; ----------------------------------------------------------\n");
    fprintf(out, "; Program compilation summary:\n");
    fprintf(out, "; Total steps consumed: %u / %u (%.1f%% memory used)\n",
            rec->count, caps->max_program_steps,
            (100.0f * rec->count) / caps->max_program_steps);
}

void export_to_keys(FILE *out, const TargetCaps *caps, const StepRecorder *rec) {
    if (!out || !caps || !rec) return;

    fprintf(out, "========================================================================\n");
    fprintf(out, "ELEKTRONIKA MK-56 PHYSICAL KEYBOARD TYPING GUIDE\n");
    fprintf(out, "Architecture: %s | Max Steps: %u | Consumed: %u (%.1f%%)\n",
            caps->architecture, caps->max_program_steps,
            rec->count, (100.0f * rec->count) / caps->max_program_steps);
    fprintf(out, "Instructions for operator: Switch to [ПРОГ] mode, press [В/О], then type:\n");
    fprintf(out, "========================================================================\n");
    fprintf(out, "Step | Keystroke Sequence       | Function / Action Description\n");
    fprintf(out, "-----+--------------------------+---------------------------------------\n");

    for (int i = 0; i < rec->count; i++) {
        const ProgramStep *s = &rec->steps[i];
        fprintf(out, " %02u  | ", s->address);
        fprint_utf8_padded(out, s->keystrokes, 24);
        fprintf(out, " | %s\n", s->description);
    }

    fprintf(out, "========================================================================\n");
    fprintf(out, "Program Entry Complete. Switch back to [АВТ] mode and press [В/О] [С/П].\n");
    fprintf(out, "========================================================================\n");
}

void export_to_hex(FILE *out, const TargetCaps *caps, const StepRecorder *rec) {
    if (!out || !caps || !rec) return;

    fprintf(out, "; MK-56 Raw Bytecode Image for Software Emulators\n");
    fprintf(out, "; Total bytes: %d\n", rec->count);

    for (int i = 0; i < rec->count; i++) {
        if (i % 8 == 0) {
            if (i > 0) fprintf(out, "\n");
            fprintf(out, "%02u: ", (uint8_t)i);
        }
        fprintf(out, "%02X ", rec->steps[i].opcode);
    }
    fprintf(out, "\n");
}

#include "regalloc.h"

bool export_all_files(const char *base_filename, const TargetCaps *caps, const StepRecorder *rec) {
    if (!base_filename || !caps || !rec) return false;

    char asm_name[512];
    char keys_name[512];
    char hex_name[512];

    /* Strip any trailing extension if present */
    char clean_base[256];
    snprintf(clean_base, sizeof(clean_base), "%s", base_filename);
    char *dot = strrchr(clean_base, '.');
    if (dot && (strcmp(dot, ".mk56") == 0 || strcmp(dot, ".keys") == 0 ||
                strcmp(dot, ".hex") == 0 || strcmp(dot, ".c") == 0)) {
        *dot = '\0';
    }

    snprintf(asm_name, sizeof(asm_name), "%s.mk56", clean_base);
    snprintf(keys_name, sizeof(keys_name), "%s.keys", clean_base);
    snprintf(hex_name, sizeof(hex_name), "%s.hex", clean_base);

    FILE *f_asm = fopen(asm_name, "w");
    if (f_asm) {
        export_to_asm(f_asm, caps, rec);
        regalloc_dump_intervals(f_asm);
        fclose(f_asm);
    }

    FILE *f_keys = fopen(keys_name, "w");
    if (f_keys) {
        export_to_keys(f_keys, caps, rec);
        fclose(f_keys);
    }

    FILE *f_hex = fopen(hex_name, "w");
    if (f_hex) {
        export_to_hex(f_hex, caps, rec);
        fclose(f_hex);
    }

    return true;
}
